            </p>
            <p>
                Helps your organization examine the effectiveness of your processes <br>
                Establishes priorities for improvement <br>
                Helps you implement these improvements <br>
            </p>
            <p>
                <b>How CMMI is different:</b>  The CMMI provides an integrated, consistent, enduring framework for enterprise-wide process improvement and can accommodate new initiatives as future needs are identified. Unlike single-discipline or stove-pipe models that can result in confusion and higher costs when implemented together.
            </p>
            <p>
                <b>Who it is for:</b> Those providing systems and software engineering products and services to organizations who transform customer needs expectations, and constraints into products, and supporting these products throughout their life. If you manufacture, code, analyze, maintain or document a product, you need this!
            </p>
